function M.apply_polar(w, profile_name, caliber, mass, length)
    local src = M[profile_name] or M.FM_AAM_BVR
    local fm = deep_copy(src)
    fm.caliber = caliber
    fm.mass = mass
    if fm.S then
        fm.S = math.pi * (caliber * 0.5) * (caliber * 0.5)
        fm.L = caliber
    else
        fm.L = length
        fm.I = math.max(35.0, (mass * length * length) / 12.0)
    end
    w.fm = fm
end

return M
